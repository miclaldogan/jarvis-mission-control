class NewsPack(RulePack):
    """News-driven awareness task rules.
    
    Rules:
    - ai_regulation_brief: AI regulation news → summarize
    - tech_layoffs_impact: Layoff news → impact analysis
    - security_alert: Security breach → review own systems
    - general_brief: Top news → 5min summary
    """
    
    name = "news"
    description = "News-driven awareness and briefing rules"
    
    def evaluate(self, context: dict[str, Any], preferences: dict[str, Any] = None) -> list[GeneratedMission]:
        preferences = preferences or {}
        missions = []
        news = context.get("news") or []
        
        if not news:
            return missions
        
        # Combine all titles for keyword search
        all_titles = " ".join([
            (n.get("title", "") if isinstance(n, dict) else str(n)).lower()
            for n in news
        ])
        
        # Rule: ai_regulation_brief
        ai_keywords = ["ai regulation", "artificial intelligence", "gpt", "llm", "openai", "eu ai act", "ai safety"]
        if any(kw in all_titles for kw in ai_keywords):
            matched = next((kw for kw in ai_keywords if kw in all_titles), "AI")
            missions.append(GeneratedMission(
                title="AI gündem özeti hazırla (5dk)",
                priority="P3",
                category="study",
                energy_cost="medium",
                duration_minutes=10,
                deadline_hours=8,
                tags=["news", "ai", "briefing", "awareness"],
                why=f"📰 '{matched.title()}' ile ilgili haberler var. Kısa özet hazırlamak stratejik farkındalık sağlar.",
                pack_name=self.name,
                rule_name="ai_regulation_brief",
                sources=["news"],
                confidence=0.7,
            ))
        
        # Rule: tech_layoffs_impact
        layoff_keywords = ["layoff", "layoffs", "job cuts", "workforce reduction", "downsizing"]
        if any(kw in all_titles for kw in layoff_keywords):
            missions.append(GeneratedMission(
                title="Sektör işten çıkarma haberleri: etki analizi",
                priority="P3",
                category="work",
                energy_cost="medium",
                duration_minutes=15,
                deadline_hours=24,
                tags=["news", "career", "analysis"],
                why="💼 Tech sektöründe işten çıkarma haberleri var. Kendi pozisyon ve network'ünü gözden geçir.",
                pack_name=self.name,
                rule_name="layoff_impact",
                sources=["news"],
                confidence=0.6,
            ))
        
        # Rule: security_alert
        security_keywords = ["data breach", "hack", "vulnerability", "cyber attack", "ransomware", "security flaw"]
        if any(kw in all_titles for kw in security_keywords):
            matched = next((kw for kw in security_keywords if kw in all_titles), "security")
            missions.append(GeneratedMission(
                title="Güvenlik kontrolü: sistemleri gözden geçir",
                priority="P2",
                category="dev",
                energy_cost="medium",
                duration_minutes=20,
                deadline_hours=4,
                tags=["news", "security", "audit", "critical"],
                why=f"🔒 '{matched.title()}' haberi var. Kendi sistemlerinde benzer zafiyet kontrolü yap.",
                pack_name=self.name,
                rule_name="security_review",
                sources=["news"],
                confidence=0.75,
            ))
        
        # Rule: general_brief
        if news and len(news) > 0:
            top_title = news[0].get("title", "gündem") if isinstance(news[0], dict) else str(news[0])
            missions.append(GeneratedMission(
                title="Gündemi tara: 5dk hızlı okuma",
                priority="P4",
                category="study",
                energy_cost="low",
                duration_minutes=5,
                deadline_hours=12,
                tags=["news", "awareness", "daily"],
                why=f"📱 Günün öne çıkan haberi: '{top_title[:50]}...'",
                pack_name=self.name,
                rule_name="general_brief",
                sources=["news"],
                confidence=0.5,
            ))
        
        return missions


# Registry of all rule packs
RULE_PACKS: list[RulePack] = [
    WeatherPack(),
    CalendarPack(),
    GitHubPack(),
    NewsPack(),
]


def evaluate_all_packs(context: dict[str, Any], preferences: dict[str, Any] = None) -> list[GeneratedMission]:
    """Evaluate all rule packs against context and return all generated missions."""
    all_missions = []
    
    for pack in RULE_PACKS:
        try:
            missions = pack.evaluate(context, preferences)
            all_missions.extend(missions)
        except Exception as e:
            # Log but don't fail
            print(f"Error in pack {pack.name}: {e}")
    
    return all_missions


def find_scheduling_conflicts(missions: list[GeneratedMission], calendar_events: list[dict]) -> None:
    """Update missions with scheduling conflicts based on calendar."""
    if not calendar_events:
        return
    
    for mission in missions:
        if mission.suggested_time:
            # Simple conflict detection (could be more sophisticated)
            for event in calendar_events:
                event_time = event.get("time", "")
                if event_time and mission.suggested_time and event_time in mission.suggested_time:
                    mission.conflicts.append(f"Çakışma: {event.get('title', 'Event')} @ {event_time}")
